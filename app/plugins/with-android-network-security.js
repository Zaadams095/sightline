// Lets Sightline talk plain HTTP to cameras and recorders on Android.
//
// Android blocks cleartext (http://) traffic by default. Sightline needs it:
//  - cameras, doorbells and NVRs on a home network almost always serve their API over plain
//    HTTP, at addresses the person types or the app discovers (192.168.x.x, 10.x.x.x,
//    172.16-31.x.x, "nvr.local", a NAS hostname...);
//  - the WireGuard tunnel's gateway listens on loopback (http://127.0.0.1:<port>) and
//    forwards to the camera, so every remote view is cleartext to 127.0.0.1;
//  - in development, Metro on the computer is plain HTTP too.
//
// Android's network security config can only allow cleartext per domain name or exact IP
// address, not per range (no CIDR), and the addresses aren't known when the app is built, so a
// domain-config list can't cover them. The base config therefore permits cleartext. Nothing
// sensitive leaves the phone in the clear because of this: Sightline's own services (the Hub
// remotely, Expo, Firebase) use HTTPS, and LAN/tunnel traffic stays on the home network or
// inside WireGuard. Certificates are still checked against the system store (self-signed
// camera HTTPS goes through the tunnel's own proxy, which handles that per camera).
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-network-security.js. Why cleartext is allowed: see there. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withNetworkSecurityFile(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), XML);
      return cfg;
    },
  ]);
}

function withNetworkSecurityManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    // Read only by Android 6 and older, which ignore the config file; kept consistent.
    app.$['android:usesCleartextTraffic'] = 'true';
    return cfg;
  });
}

module.exports = function withAndroidNetworkSecurity(config) {
  return withNetworkSecurityManifest(withNetworkSecurityFile(config));
};
